/**
 * 阶梯偏移（层深 k ≥ 0，可连续）：几何级数，保证「露出越来越少」。
 * stair(0)=0、stair(1)=0.19·cardW、stair(2)=0.2508·cardW、stair(3)=0.2703·cardW
 * （第六轮：0.19 / 0.2508 / 0.2703，露出 52 : 17 : 5 px；旧 0.12 / 0.186 / 0.222，露出 33 : 18 : 10）
 *
 * 它同时决定了【一层过渡里各层的右移量】：
 *   depth-1 卡位移 = stair(1) − stair(0) = stair(1)
 *   depth-2 卡位移 = stair(2) − stair(1)
 *   depth-3 卡位移 = stair(3) − stair(2)
 * 因为 aEff = d − u 从 d 走到 d−1，位置的净变化就是相邻两级 stair 之差。
 * 这条链是「位移递减」的唯一来源 —— 一旦再叠加会归零的包络，就会产生回退（定律三）。
 */
export function deckStair(k, cardW) {
  const c = (DECK.STAIR_BASE_FRAC * cardW) / (1 - DECK.STAIR_DECAY)
  return c * (1 - Math.pow(DECK.STAIR_DECAY, Math.max(0, k)))
}

/**
 * 屏幕尺寸 → 几何度量。
 *
 * 垂直布局（修正 A/B/C）：
 *   blockH  = 图标行 + 间隙 + 卡高
 *   gap     = (删除按钮顶 - 状态栏底 - blockH) / 2      ← 上下留白相等 = 整体居中
 *   labelY  = 状态栏底 + gap                            ← 图标行顶部
 *   cardY   = labelY + 图标行 + 间隙                     ← 卡顶（scale = 1 时）
 *   cardCy  = cardY + cardH / 2                          ← 所有层共用的垂直中心
 *
 * @param opts.topInset   状态栏底部（px，实测 --safe-top）
 * @param opts.homeInset  home indicator 高度（px）
 * @param opts.dockSize   删除按钮直径（px）
 */
export function deckMetrics(screenW, screenH, opts = {}) {
  const cardW = Math.round(screenW * DECK.CARD_W_FRAC)
  const cardH = Math.round(screenH * DECK.CARD_H_FRAC)
  const radius = Math.round(screenW * DECK.RADIUS_FRAC)

  const dockSize = opts.dockSize ?? DECK.DOCK_SIZE
  const homeInset = opts.homeInset ?? DECK.DEFAULT_HOME_INSET
  const dockTop = screenH - homeInset - DECK.DOCK_GAP - dockSize
  const topInset = opts.topInset ?? Math.round(screenH * DECK.TOP_INSET_FRAC)

  const blockH = DECK.LABEL_ROW_H + DECK.LABEL_GAP + cardH
  const gap = Math.max(0, (dockTop - topInset - blockH) / 2)
  const labelY = topInset + gap
  const cardY = labelY + DECK.LABEL_ROW_H + DECK.LABEL_GAP
  const cardCy = cardY + cardH / 2

  return {
    screenW,
    screenH,
    cardW,
    cardH,
    cardY,
    cardCy,
    labelY,
    dockTop,
    topInset,
    gap,
    blockH,
    frontX: (screenW - cardW) / 2, // 焦点层左边缘（= 水平居中）
    radius,
    /* 离场槽距（第八轮）= **0.89 卡宽**（= 0.57 屏宽 @430 ⇒ 245px）：
       restX(-1) = frontX + 245 = 322.5px，比居中卡右缘（352.5）小 30px
       ⇒ 离场卡压住 C 位约 10.9%，即 Ricky 需求②的「遮挡 C 位约 10%」。
       （第七轮是 0.64 屏宽 = 一张卡宽 = 刚好贴住；本轮有意反转成重叠。） */
    exit: Math.round(screenW * DECK.EXIT_FRAC),
    span: cardW * DECK.FOCUS_SPAN_FRAC,
    previewScale: screenW ? cardW / screenW : 1
  }
}

/**
 * 层过渡进度（定律一）：把焦点的【小数部分】映射成两件东西共用的进度。
 *   m = 焦点所在整数层
 *   x = 原始小数进度（0..1）
 *   u = x^TRANS_POW —— 顶卡退出斜坡与背景层推进【共用】的进度
 *
 * 背景层的连续层深用 aEff = a + (x − u) 计算。对每张卡，a = d − x（d = i − m 为整层深度），
 * 所以 aEff 恒等于 d − u：随 u: 0→1 严格单调递减 → 位置单调右移、缩放单调变大（定律三）。
 * 在 x=0 / x=1 两端 aEff 分别等于 d 与 d−1，与层边界的整数层深重合 → 零跳变。
 */
export function deckPhase(focus) {
  const m = Math.floor(focus)
  const x = Math.min(Math.max(focus - m, 0), 1 - 1e-9)
  return { m, x, u: Math.pow(x, DECK.TRANS_POW) }
}

/**
 * 单张卡的位姿。
 * @param a     层深 a = i - focus（连续，可负）
 * @param m     deckMetrics(...)
 * @param xFrac 焦点的小数进度（0..1，来自 deckPhase(focus).x）—— 顶卡退出与背景推进共用
 */
export function deckPose(a, m, xFrac = 0) {
  const x = Math.min(Math.max(xFrac, 0), 1 - 1e-9)
  const u = Math.pow(x, DECK.TRANS_POW) // 层过渡进度（定律一）

  /* 第十轮·需求③：左滑挤压的两个几何分量（k = 挤压进度，允许弹簧过冲到负）。
     · g     —— 整组等比缩小（实测 0.951）
     · tight —— 阶梯收紧（槽距乘它，「漏出的多少」变小）
     两者都由 deckSqueeze* 给出，和 deckSqueezeShift 的位移共用一个 k ⇒ 缩放/收紧/位移
     永远同相位，不会出现「先挪再缩」的错拍。 */
  const g = deckSqueezeScale(m.sq)
  const tight = deckSqueezeTighten(m.sq)

  let restX
  let scale
  let depth
  if (a >= 0) {
    /* 背景层（定律三：纯槽位推进，不得回退）。
       aEff = a + (x − u) = d − u —— 随 u 单调递减，因此：
         · restX = frontX − stair(aEff) 单调递增（一路向右，绝不回退）；
         · scale = 0.94^aEff 单调递增（与位移【同时】发生，不是先位移后放大）。
       缩放与位移共用同一个 u，这就是「被顶卡拖着走 + 同时放大」的全部机制；
       旧版额外叠加的牵连包络必须在一层末尾归零，那正是「往右滑却往左走」的根因。 */
    const aEff = Math.min(Math.max(a + (x - u), 0), DECK.MAX_DEPTH)
    /* 阶梯间距乘 tight（第十轮）：挤压时背景卡往中间拢，「漏出的多少」随之变小。
       ⚠️ 收紧的是【槽距】，不是 frontX —— frontX 是前卡自己的位置，动它会连带
       影响「前卡在屏幕上的落点」，那是位移分量的事。 */
    restX = m.frontX - deckStair(aEff, m.cardW) * tight
    scale = Math.pow(DECK.SCALE_DECAY, aEff)
    depth = aEff
  } else {
    /* 离场斜坡：比焦点更新的卡往右离开屏幕。
       EXIT_POW = 1（线性）⇒ 位移 = 一张卡宽 × |a|。
       |a| 不夹到 1 —— 旧版 `Math.min(1, -a)` 是配合 0.88 屏宽的「一次飞出」模型，
       那个夹取会让第 2、3 张离场卡全部堆在同一个 x 上（永远出不了屏）。
       第七轮·批次 4（exit = 一张卡宽 = 275px，需求②）：
         a = −1 → 左缘 = frontX + 275 = **352.5 = 居中卡右缘**（刚好贴住、零重叠），
                  屏内仍露出 430 − 352.5 = **77.5px** 的边；
         a = −2 → frontX + 550 = 627.5 > 430，真正出屏，逐张向外铺开。 */
    restX = m.frontX + m.exit * Math.pow(-a, DECK.EXIT_POW)
    scale = 1
    depth = 0
  }

  /* 等比缩小（第十轮）：乘在【本层缩放】之后 ⇒ 背景卡的「自身层级缩放 × 整组缩小」
     两者叠加，前卡也一起缩（实测前卡就是缩了 ≈5%）。
     ⚠️ 堆叠卡的原点是 0 0（左缘钉住），所以逐卡缩小【只往右收右边缘】，
        左缘仍停在 restX —— 「漏出的多少」因此【不】由这里承担，而由 tight 承担。
        两者分工：g = 卡片大小，tight = 露出宽度。原话「缩小底层卡片大小以及漏出的多少」
        正好就是这两项。 */
  scale *= g

  return {
    a,
    depth,
    x: restX,
    /* 修正 B：所有层共用同一个垂直中心（cardCy），缩放造成的内缩上下对称 ——
       「所有卡片与顶部卡片上下居中对齐」。旧版 y = cardY + yStep·depth 是顶对齐 +
       向下偏移，背景层整体浮在上方，正是 Ricky 指出的问题。 */
    y: m.cardCy - (m.cardH * scale) / 2,
    scale,
    bright: 1 - DECK.BRIGHT_STEP * depth,
    z: 0
  }
}

/** 层级：只由列表索引决定（规则①），i 越小越靠上 */
export function deckZ(i) {
  return DECK.Z_BASE - i
}

/** 该层是否需要渲染 —— 规则⑤「同时最多三层」。
 *  只渲染层深 a ∈ (-EXIT_CULL, MAX_DEPTH] 的卡：0/1/2 正好是三个槽位，
 *  层深 > 2 的第 4 张必须剔除（否则它会在第 3 层左侧再露出第四道阶梯）。
 *  负半区保留到 -EXIT_CULL（第七轮·批次 4：-1.56 → -1.30）—— 右侧槽距改成
 *  「一张卡宽」(275px) 后，离场卡走到 a ≈ -1.28125（左缘 = 77.5 + 275×1.28125 ≈ 430）
 *  才真正出屏，所以剔除界同步收到 -1.30，保证「还看得见就一定有 DOM」（否则会闪断）。 */
export function deckVisible(a) {
  return a > -DECK.EXIT_CULL && a <= DECK.MAX_DEPTH
}

/* ── 第八轮新增、第九/十轮两次改语义的纯函数 ───────────────────────────── */

/**
 * 左滑越界 → 挤压进度 k（需求③）。
 * @param over 越界层数 = max(0, −focus)，由 deckClampFocus 限制在 [0, 0.6]
 * @returns k ∈ [0, 1]：0 = 不挤压，1 = 满挤压
 *
 * k 是【三个几何分量的共同自变量】，不再直接等于某一种形变：
 *   deckSqueezeScale(k)   → 等比缩小系数（1 → 0.951）
 *   deckSqueezeTighten(k) → 阶梯收紧系数（1 → 0.45）
 *   deckSqueezeShift(...) → 整组左移量（0 → −(screenW − cardW)/2 = −frontX）
 * 三者共用一个 k ⇒ 缩放/收紧/位移永远同相位。
 *
 * ⚠️ 历史（别再走回去）：
 *   · 第八轮把这一个量当成 `scaleX`（1 → 0.84）⇒ 卡被「压扁」（Ricky 原话）。
 *   · 第九轮改成「只有整组左移」⇒ 又漏了缩放与阶梯收紧（Ricky 第十轮原话：
 *     「需要同时做横向挤压和缩放」）。
 * 副作用（第八轮修好、后续保留）：焦点被冻结在 0 ⇒ 层深恒 ≤ MAX_DEPTH ⇒ 最底部卡片不被剔除。
 *
 * ── 第十七轮：为什么必须给它加【死区 + smoothstep】──────────────────────────
 * Ricky 原话：「横滑切换疯狂抖动。。。」（附 7.2s 录屏）。
 *
 * 症状（逐帧量测录像 /tmp/vwork/r17/，413 帧 VFR + 真实时间戳）：
 *   · 整组卡片作为【刚体】左右抽动，单帧跳变 100~300 视频 px（= 48~144 CSS px），
 *     且在 12~30ms 内【反号】—— 远高于任何弹簧的频率（本工程最硬的 ios-snappy
 *     ω_n = 22.4 rad/s = 3.6Hz）⇒ 这不是动画，是【离散瞬移】；
 *   · 同一段里前卡视觉宽从 275 变成 263（= 0.956）⇒ 挤压态（SQUEEZE_SCALE_MAX 4.9%）
 *     确实在反复咬合/释放；
 *   · 尾部还有一段 ±50 视频 px（±24 CSS px）的衰减振荡。
 * 复现（探针 /tmp/vwork/r17/probe-zig.mjs，模式 z2：在 x=420 按下 → 拖到 x=20 →
 *   拉回 x=80，来回 8 次，即「贴着第一张卡反复横滑」）：
 *     focus 范围 −0.599~0.000（吃满 deckClampFocus 的 −0.6 钳位）
 *     tr.e  范围 −77.5~+14.5，**单帧最大跳变 = 77.50px** ← 就是录像里那 162 视频 px
 *
 * 根因（两个缺陷叠加，都在这个函数与它的调用点）：
 *   ① 【导数拐点】原式 = clamp(over / SPAN) 在 over = 0 处斜率从 0 跳到 1/0.35 = 2.86
 *      ⇒ 一个「bang-bang 边界」。而 deckClampFocus 把越界量压成手指行程的 0.35 倍，
 *      于是 14px 的手指抖动就能换到 0.04 层的越界 ⇒ 挤压进度 0.114 ⇒ 整组位移 8.8px。
 *      这条通道的增益是【221px 位移 / 层越界】，是组件里放大倍数最高的一条。
 *   ② 【瞬写】调用点 dragSqueeze() 用的是 sqSnap（零过渡直写，见 AppSwitcher）——
 *      所以增益 221 是把【输入抖动 1:1 变成整组瞬移】，没有任何时间域平滑。
 *   而「越界时卡片本身不动」（poseFocus = max(0, focus) 把卡片位姿钉在 0）
 *   ⇒ 这一段屏幕上【只有整组在动】⇒ 读起来就是「卡片冻住 → 整块啪地跳一下」。
 *
 * 本函数负责 ①：把进度曲线改成【死区 + smoothstep】——端点导数也为 0，没有拐点，
 *   越界量在死区内一律输出 0，刚出死区时增益从 0 连续长起来。
 *   ⚠️ ② 由 AppSwitcher 的 dragSqueeze 用【逐帧限速】解决（每帧最多变 SQ_MAX_STEP）。
 *      两者都不能省：单靠 ①，满量程的 77.5px 瞬移照旧（它是 0→1 的整段跳）；
 *      单靠 ②，小抖动的幅度仍被 221px/层 如实放大（只是被摊到几帧）。
 *
 * 契约不变（单测已锁）：deckSqueeze(0) = 0、deckSqueeze(SPAN) = 1、更深封顶 1、全程非减。
 */
export function deckSqueeze(over) {
  const a = Math.max(0, over)
  const z = DECK.SQUEEZE_DEAD_ZONE
  if (a <= z) return 0
  /* 归一化到 [0,1] 后走 smoothstep（3t²−2t³）：两端导数都是 0 ⇒ 与死区、与封顶处都 C¹ 相接。
     ⚠️ 分母是 SPAN − z（不是 SPAN），否则 a = SPAN 时到不了 1 ⇒ 满挤压位移差几 px。 */
  const t = Math.min(1, (a - z) / (DECK.SQUEEZE_SPAN - z))
  return t * t * (3 - 2 * t)
}

/** 挤压进度的允许区间：ios-squish 的过冲会让 k 短暂为负/超过 1，
 *  下界留 0.35（回弹）、上界留 1.35（弹簧被高速注入时也不把整组甩出屏）。
 *  三个分量（位移/缩放/收紧）共用这一个钳制，保证它们永远同相位、不脱钩。 */
function clampSqueezeK(k) {
  return Math.min(1.35, Math.max(-0.35, k || 0))
}

/**
 * 挤压进度 → 整组等比缩小系数（第十轮·需求③）。
 * @returns g ∈ [0.934, 1.017]（k 被钳在 [−0.35, 1.35]），
 *          1 = 原尺寸，满挤压 = 1 − 0.049 = **0.951**（实测前卡高 654→622 = 0.951）
 *
 * ⚠️ 这个乘数【乘在每张卡自己的 transform 上】，而堆叠卡是 `transform-origin: 0 0`
 *    （左缘钉住，见 .switcher-card.is-deck）—— 所以它**不会**把卡的左缘往右推。
 *    （历史上这里写着「围绕自身中心缩放 ⇒ 左右缘对称内缩」，是错的，别再照抄直觉。）
 *    真实可见效果两处：
 *      · 前卡：右缘左收 cardW·0.049 ≈ 13.5px（垂直方向由 deckPose 的
 *        y = cardCy − cardH·scale/2 补偿 ⇒ 上下缘对称内缩，与实测 131→147 / 785→769 一致）；
 *      · 背景卡：左缘【不动】（被 stair·tight 定位），可见的「露出条」
 *        纵向变矮 4.9% —— 那条 23~52px 宽的竖带在眼睛里的观感就是「底层卡片变小了」。
 *    背景卡的水平宽窄看不出差别（它右半边本就压在前卡底下），别去调 g 求这个效果。
 */
export function deckSqueezeScale(k) {
  return 1 - DECK.SQUEEZE_SCALE_MAX * clampSqueezeK(k)
}

/**
 * 挤压进度 → 阶梯收紧系数（第十轮·需求③）。
 * @returns tight ∈ [0.55, 1.193]（k 被钳在 [−0.35, 1.35]），
 *          1 = 原槽距，满挤压 = 1 − 0.55 = **0.45**
 *
 * 乘在 deckStair 上：槽距 52 : 17 : 5px → 23 : 8 : 2px，背景卡整体往中间「拢」。
 * 这是原话里「漏出的多少」的另一半来源（另一半是上一行的逐卡缩小）。
 */
export function deckSqueezeTighten(k) {
  return 1 - DECK.SQUEEZE_TIGHTEN * clampSqueezeK(k)
}

/**
 * 挤压进度 → 卡片组整体左移量（px，负 = 向左）。
 *
 * shift = −frontX × min(k, 1) = −(screenW − cardW)/2 × min(k, 1)
 *   ⇒ k = 1 时前卡的视觉左缘正好落到屏幕左缘（= 0）。
 *
 * ⚠️ 为什么【不】与等比缩小系数 g 耦合（本轮一开始写错过）：
 *    堆叠卡是 `transform-origin: 0 0`（左缘钉住，见 .switcher-card.is-deck），
 *    所以逐卡缩放【不会】移动它自己的左缘 —— frontX 与 g 无关。
 *    （若写成 −(screenW − cardW·g)/2 就会多推 6.75px，把前卡左缘推到 −6.75。
 *      这个式子只在 origin 为 center 时才对，别照搬直觉。）
 * 为什么上过冲（k > 1）位移封顶：压缩还能继续加深，但「左缘贴住屏左缘」已经是行程上限，
 *    再往左就是白送出屏；下过冲（k < 0，ios-squish 回弹）不封顶 —— 整组向右弹回去。
 */
export function deckSqueezeShift(screenW, cardW, k) {
  const kk = clampSqueezeK(k)
  if (kk === 0) return 0 // 归一掉 −0（否则单测的 Object.is 严格比较与 CSS 字符串都会带 −0）
  return -((screenW - cardW) / 2) * Math.min(kk, 1)
}

/** 卡片组整体藏到屏幕左侧时的 x 偏移（需求⑤⑥：入/退场都是横向平移 0.78 屏宽） */
export function deckEnterDx(screenW) {
  return -Math.round(screenW * DECK.EXIT_SLIDE_FRAC)
}

/** 越界阻尼：0..n-1 之外按指数压扁，手感接近 iOS 橡皮筋 */
export function deckClampFocus(raw, n) {
  const last = Math.max(0, n - 1)
  if (raw < 0) return Math.max(-0.6, raw * DECK.RUBBER)
  if (raw > last) return Math.min(last + 0.6, last + (raw - last) * DECK.RUBBER)
  return raw
}

/** 卡片（含最深层）的左边缘最小值 —— 规则③的静态保证（牵连只会往右推，不会破坏它） */
export function deckMinLeftEdge(m) {
  return m.frontX - deckStair(DECK.MAX_DEPTH, m.cardW)
}

/* ── 第二十一轮：手势输入的【坐标连续性】判据（纯函数，AppSwitcher 与单测共用）────────
 *
 * 用途：多任务页横滑时，owner 指针的 clientX 有可能在**没有任何 pointerdown** 的情况下
 *   跳到另一根手指的坐标上（两个触摸点被合并成一条坐标流，或指针被重定向到另一指）。
 *   实测（/tmp/vwork/r21/probe-sameid.mjs，CDP 注入两个同 id 的触点）：
 *     T2/T2b/T3 三条场景 **单帧最大 Δfocus = 0.565 层 = 119.9px**，而事件流里
 *     `pointerdown 计数 = 1`、`出现的 pointerId = [4]`、`touchstart` 的 touches 只有 1 个
 *     ⇒ 页面侧**完全看不见第二根手指**，任何基于 pointerId / isPrimary / touches.length
 *     的守卫都不可能覆盖（第二十轮的 owner 守卫就是这一类，所以它挡不住）。
 *
 * 判据（只用「已应用位移」的历史做参考，因此与事件频率无关）：
 *   ① 本笔的坐标跳变 ≥ TOUCH_STEP_JUMP_PX（56px —— 单帧手指数值上几乎到不了）；
 *   ② 且 ≥ TOUCH_STEP_RATIO 倍于【最近若干笔已应用位移的最大值】。
 * 两条同时成立 ⇒ 判定为「坐标不连续」，调用方应当只把基线平移到新坐标、不让这段位移进焦点。
 *
 * 为什么用 max 而不是中位数：手指【渐进加速】时（13 → 25 → 40 → 60px/帧）参考量会跟着抬，
 *   于是真实的加速永远不触发；只有「在一串小步之后突然出现 3 倍以上的巨步」才触发
 *   —— 那正是换指/合并的形状（13,13,13,+120），也是物理上手指做不到的形状。
 * ⚠️ 参考量必须喂「已应用位移」（被守卫吸收的那一笔记 0），否则连续抽动会把参考量抬高，
 *    第二笔就再也认不出来了（两指来回抽动的形状 = +120, −120, +120…）。
 * ⚠️ 前 TOUCH_STEP_WARMUP 笔不判（比例判据）：① 参考量还没有意义；② 触摸 slop 释放的第一帧
 *    本身就可能有 8~12px 的位移（见 MODE_LOCK_PX 的注释），不该被卷入判定。
 *    热身期只有「巨步兜底」这一条兜着（见实现）。 */
export const TOUCH_STEP_JUMP_PX = 56
export const TOUCH_STEP_RATIO = 3
export const TOUCH_STEP_WARMUP = 3
/** 参考量的取样窗口（最近多少笔【已应用】位移）—— 5 笔 ≈ 80ms @60Hz，够反映当前手速 */
export const TOUCH_STEP_KEEP = 5

export function touchStepIsTeleport(jump, applied) {
  const j = Math.abs(jump)
  if (!(j >= TOUCH_STEP_JUMP_PX)) return false
  /* 巨步兜底（≥ 2×56px = 112px）：热身期也判。
     一帧 112px @60Hz = 6720px/s，指尖要在一帧内从 0 加速到 6720px/s（≈43g）——
     物理上做不到，所以这一档不必再看参考量；它同时覆盖「两指落下后第一帧就被合并」的时序。 */
  if (j >= TOUCH_STEP_JUMP_PX * 2) return true
  if (!applied || applied.length < TOUCH_STEP_WARMUP) return false
  let ref = 0
  for (const s of applied) ref = Math.max(ref, Math.abs(s))
  return j >= ref * TOUCH_STEP_RATIO
}

/** 焦点层与第 k 层的露出宽度（用于「露出越来越少」断言） */
export function deckExposure(k, cardW) {
  return deckStair(k, cardW) - deckStair(k - 1, cardW)
}
